#!/usr/bin/env python3
"""Bake TTF fonts into 8-bit alpha glyph tables (fonts/fonts.c).

Run once when changing fonts; the output is committed so the build needs no
TTFs.  Glyph y offsets are relative to the top of the line box.
"""
import os, sys
from PIL import Image, ImageDraw, ImageFont

HOME = os.path.expanduser("~")
NOTO = "/usr/share/fonts/noto/"
JB = HOME + "/.local/share/fonts/JetBrainsMono/"
FONTS = [  # (c name, ttf, px)
    ("font_mono",      JB + "JetBrainsMonoNLNerdFontMono-Regular.ttf", 15),
    ("font_mono_bold", JB + "JetBrainsMonoNLNerdFontMono-Bold.ttf", 15),
    ("font_ui",        NOTO + "NotoSans-Regular.ttf", 15),
    ("font_ui_bold",   NOTO + "NotoSans-Bold.ttf", 15),
    ("font_title",     NOTO + "NotoSans-Bold.ttf", 22),
    ("font_big",       NOTO + "NotoSans-Medium.ttf", 52),
]

def bake(name, path, px):
    f = ImageFont.truetype(path, px)
    asc, desc = f.getmetrics()
    glyphs, alpha = [], bytearray()
    for code in range(32, 127):
        ch = chr(code)
        adv = round(f.getlength(ch))
        x0, y0, x1, y1 = f.getbbox(ch, anchor="la")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        off = len(alpha)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255, anchor="la")
            alpha += im.tobytes()
        glyphs.append([w, h, x0, y0, adv, off])
    # tighten the line box to the real ASCII extents (font metrics can be huge)
    ymin = min(g[3] for g in glyphs if g[1])
    ymax = max(g[3] + g[1] for g in glyphs if g[1])
    pad = round(px * 0.2)
    for g in glyphs:
        g[3] = g[3] - ymin + pad // 2
    asc, desc = asc - ymin + pad // 2, ymax - ymin + pad - (asc - ymin + pad // 2)
    out = [f"static const uint8_t {name}_alpha[{max(1, len(alpha))}] = {{"]
    for i in range(0, len(alpha), 24):
        out.append("    " + ",".join(str(b) for b in alpha[i:i + 24]) + ",")
    out.append("};")
    out.append(f"const struct font {name} = {{ {asc + desc}, {asc}, {name}_alpha, {{")
    for g in glyphs:
        out.append("    {%d,%d,%d,%d,%d,%d}," % tuple(g))
    out.append("} };\n")
    return "\n".join(out)

src = ['/* generated by tools/mkfont.py from OFL fonts (JetBrains Mono, Noto Sans) - do not edit */',
       '#include "font.h"', ""]
hdr = ["/* generated by tools/mkfont.py */", "#pragma once", "#include <stdint.h>", "",
       "struct glyph { uint8_t w, h; int8_t xoff, yoff; uint8_t adv; uint32_t off; };",
       "struct font { int height, ascent; const uint8_t *alpha; struct glyph g[95]; };", ""]
for name, path, px in FONTS:
    src.append(bake(name, path, px))
    hdr.append(f"extern const struct font {name};")
open("common/fonts.c", "w").write("\n".join(src))
open("common/font.h", "w").write("\n".join(hdr) + "\n")
print("ok", os.path.getsize("fonts/fonts.c"))
