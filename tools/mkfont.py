#!/usr/bin/env python3
"""Bake TTF fonts into 8-bit alpha glyph tables (fonts/fonts.c).

Run once when changing fonts; the output is committed so the build needs no
TTFs.  Glyph y offsets are relative to the top of the line box.
"""
import os, sys
from PIL import Image, ImageDraw, ImageFont

HOME = os.path.expanduser("~")
NOTO = "/usr/share/fonts/noto/"
JB = HOME + "/.local/share/fonts/JetBrainsMono/"
# non-ASCII extras, kept small: every GUI binary links these tables statically
COMMON = ("".join(chr(c) for c in range(0xA1, 0x100)) + "–—‘’“”•…‹›←↑→↓↔↵⇧−≈≠≤≥∞√"
          "✓✔✗✘★☆♥♪●○◆◇■□▲▼▶◀►◄❯❮⌫⏎░▒▓█▀▄▌▐")
SMALL = "×÷−±·°•…→←✓✗"
FONTS = [  # (c name, ttf, px, extras)
    ("font_mono",      JB + "JetBrainsMonoNLNerdFontMono-Regular.ttf", 15, COMMON + "\ue0b0\ue0b1\ue0b2\ue0b3"),
    ("font_mono_bold", JB + "JetBrainsMonoNLNerdFontMono-Bold.ttf", 15, COMMON + "\ue0b0\ue0b1\ue0b2\ue0b3"),
    ("font_ui",        NOTO + "NotoSans-Regular.ttf", 15, COMMON),
    ("font_ui_bold",   NOTO + "NotoSans-Bold.ttf", 15, COMMON),
    ("font_title",     NOTO + "NotoSans-Bold.ttf", 22, SMALL),
    ("font_big",       NOTO + "NotoSans-Medium.ttf", 52, "×÷−±·°"),
]

# extra terminal sizes for Ctrl+= / Ctrl+- (termfonts.c is linked into the kernel only; the 15px cut lives in fonts.c)
ZOOM = [(f"{n}_{px}", f"JetBrainsMonoNLNerdFontMono-{w}.ttf", px, COMMON + "\ue0b0\ue0b1\ue0b2\ue0b3")
        for px in (12, 18, 22) for n, w in (("font_mono", "Regular"), ("font_mono_bold", "Bold"))]

def render_sig(f, ch):
    m = f.getmask(ch)
    return f.getlength(ch), m.size, bytes(m)

FALLBACK = [NOTO + "NotoSansSymbols2-Regular.ttf", NOTO + "NotoSansSymbols-Regular.ttf", NOTO + "NotoSansMath-Regular.ttf"]

def bake(name, path, px, extras):
    f = ImageFont.truetype(path, px)
    asc, desc = f.getmetrics()
    glyphs, alpha = [], bytearray()
    fonts = [f] + [ImageFont.truetype(p, px) for p in FALLBACK if os.path.exists(p)]
    nodef = [render_sig(ff, "\U0010fffd") for ff in fonts]     # what .notdef looks like in each
    src = {c: 0 for c in range(32, 127)}                       # codepoint -> font that has it
    for c in sorted({ord(ch) for ch in extras}):
        for i, ff in enumerate(fonts):
            if render_sig(ff, chr(c)) != nodef[i]: src[c] = i; break
    xcps = sorted(c for c in src if c >= 127)
    for code in list(range(32, 127)) + xcps:
        ch, ff = chr(code), fonts[src[code]]
        adv = round(ff.getlength(ch))
        x0, y0, x1, y1 = ff.getbbox(ch, anchor="ls")           # baseline-relative, so fallbacks line up
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        off = len(alpha)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=ff, fill=255, anchor="ls")
            alpha += im.tobytes()
        glyphs.append([w, h, x0, y0 + asc, adv, off])
    # tighten the line box to the real ASCII extents (font metrics can be huge)
    ymin = min(g[3] for g in glyphs[:95] if g[1])
    ymax = max(g[3] + g[1] for g in glyphs[:95] if g[1])
    pad = round(px * 0.2)
    for g in glyphs:
        g[3] = g[3] - ymin + pad // 2
    asc, desc = asc - ymin + pad // 2, ymax - ymin + pad - (asc - ymin + pad // 2)
    out = [f"static const uint8_t {name}_alpha[{max(1, len(alpha))}] = {{"]
    for i in range(0, len(alpha), 24):
        out.append("    " + ",".join(str(b) for b in alpha[i:i + 24]) + ",")
    out.append("};")
    n = len(xcps)
    out.append(f"static const uint32_t {name}_xcp[{max(1, n)}] = {{ " + ",".join(map(str, xcps)) + " };")
    out.append(f"static const struct glyph {name}_xg[{max(1, n)}] = {{")
    for g in glyphs[95:]:
        out.append("    {%d,%d,%d,%d,%d,%d}," % tuple(g))
    out.append("};")
    out.append(f"const struct font {name} = {{ {asc + desc}, {asc}, {name}_alpha, {{")
    for g in glyphs[:95]:
        out.append("    {%d,%d,%d,%d,%d,%d}," % tuple(g))
    out.append(f"}}, {n}, {name}_xcp, {name}_xg }};\n")
    return "\n".join(out)

src = ['/* generated by tools/mkfont.py from OFL fonts (JetBrains Mono, Noto Sans) - do not edit */',
       '#include "font.h"', ""]
hdr = ["/* generated by tools/mkfont.py */", "#pragma once", "#include <stdint.h>", "",
       "struct glyph { uint8_t w, h; int8_t xoff, yoff; uint8_t adv; uint32_t off; };",
       "/* g[] covers ASCII 32..126; xcp/xg are sorted extra codepoints (see font_glyph) */",
       "struct font { int height, ascent; const uint8_t *alpha; struct glyph g[95];",
       "              int nx; const uint32_t *xcp; const struct glyph *xg; };", ""]
for name, path, px, extras in FONTS:
    src.append(bake(name, path, px, extras))
    hdr.append(f"extern const struct font {name};")
zsrc = ['/* generated by tools/mkfont.py: terminal zoom sizes (kernel only) - do not edit */', '#include "font.h"', ""]
zhdr = ["/* generated by tools/mkfont.py */", "#pragma once", '#include "font.h"', ""]
for name, ttf, px, extras in ZOOM:
    zsrc.append(bake(name, JB + ttf, px, extras))
    zhdr.append(f"extern const struct font {name};")
open("common/termfonts.c", "w").write("\n".join(zsrc))
open("common/termfonts.h", "w").write("\n".join(zhdr) + "\n")
open("common/fonts.c", "w").write("\n".join(src))
open("common/font.h", "w").write("\n".join(hdr) + "\n")
print("ok", os.path.getsize("common/fonts.c"))
