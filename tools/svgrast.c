/* svgrast.c - host tool: rasterise a tools/mkicons.py bundle with nanosvg (third_party/nanosvg, zlib licence).
 *   svgrast IN.bundle icons.c appicons.c fileicons.c
 * S records become A8 masks, A/F records premultiplied ARGB; each output also gets its lookup function. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#define NANOSVG_IMPLEMENTATION
#include "nanosvg.h"
#define NANOSVGRAST_IMPLEMENTATION
#include "nanosvgrast.h"

static FILE *out[3];
static int sizes[3][3] = { { 16, 20 }, { 24, 32, 48 }, { 24, 32, 48 } };
static const char *pre[3] = { "s", "a", "f" };
static char *ids[3][256];
static int nid[3];
static FILE *tmp[3][3];          /* one data stream per kind and size, joined at the end */

static void die(const char *m) { fprintf(stderr, "svgrast: %s\n", m); exit(1); }

int main(int argc, char **argv) {
    if (argc != 5) die("usage: svgrast IN.bundle icons.c appicons.c fileicons.c");
    FILE *in = fopen(argv[1], "rb");
    if (!in) die("can't open bundle");
    for (int k = 0; k < 3; k++) {
        if (!(out[k] = fopen(argv[2 + k], "w"))) die("can't write output");
        for (int s = 0; s < 3; s++) if (!(tmp[k][s] = tmpfile())) die("tmpfile");
    }
    NSVGrasterizer *r = nsvgCreateRasterizer();
    char kind, id[64];
    int size, len;
    while (fscanf(in, " %c %63s %d %d", &kind, id, &size, &len) == 4) {
        fgetc(in);
        char *svg = malloc(len + 1);
        if (fread(svg, 1, len, in) != (size_t)len) die("short bundle");
        svg[len] = 0;
        int k = kind == 'S' ? 0 : kind == 'A' ? 1 : 2, s = 0;
        while (s < 3 && sizes[k][s] != size) s++;
        if (s == 3) die("unexpected size");
        if (s == 0) ids[k][nid[k]++] = strdup(id);
        NSVGimage *im = nsvgParse(svg, "px", 96);
        if (!im) die(id);
        unsigned char *px = calloc(size * size, 4);
        nsvgRasterize(r, im, 0, 0, (float)size / im->width, px, size, size, size * 4);
        FILE *f = tmp[k][s];
        fprintf(f, "    {");
        int empty = 1;
        for (int i = 0; i < size * size; i++) {
            unsigned a = px[i * 4 + 3];
            if (a) empty = 0;
            if (k == 0) fprintf(f, "%u,", a);
            else {
                unsigned c[3];
                for (int j = 0; j < 3; j++) c[j] = (px[i * 4 + j] * a + 127) / 255;
                fprintf(f, "0x%x,", a << 24 | c[0] << 16 | c[1] << 8 | c[2]);
            }
            if (i % 32 == 31) fprintf(f, "\n     ");
        }
        fprintf(f, "},\n");
        if (empty) die(id);
        nsvgDelete(im);
        free(px);
        free(svg);
    }
    static const char *T[3] = { "uint8_t", "uint32_t", "uint32_t" };
    static const char *S[3] = { "icon", "aicon", "aicon" };
    static const char *F[3] = { "icon_get", "appicon_get", "fileicon_get" };
    for (int k = 0; k < 3; k++) {
        FILE *o = out[k];
        int ns = k ? 3 : 2;
        fprintf(o, "/* generated by tools/svgrast.c from tools/mkicons.py - do not edit */\n#include \"icons.h\"\n\n");
        for (int s = 0; s < ns; s++) {
            int z = sizes[k][s];
            fprintf(o, "static const %s %s%d[%d][%d] = {\n", T[k], pre[k], z, nid[k], z * z);
            rewind(tmp[k][s]);
            for (int ch; (ch = fgetc(tmp[k][s])) != EOF; ) fputc(ch, o);
            fprintf(o, "};\n");
        }
        fprintf(o, "static const struct %s tab[%d][%d] = {\n", S[k], ns, nid[k]);
        for (int s = 0; s < ns; s++) {
            int z = sizes[k][s];
            fprintf(o, "    {");
            for (int i = 0; i < nid[k]; i++) fprintf(o, " { %d, %d, %s%d[%d] },", z, z, pre[k], z, i);
            fprintf(o, " },\n");
        }
        fprintf(o, "};\n\nconst struct %s *%s(int id, int size) {\n", S[k], F[k]);
        fprintf(o, "    if (id < 0 || id >= %d) return 0;\n    int s = 0;\n", nid[k]);
        for (int s = 1; s < ns; s++) fprintf(o, "    if (size >= %d) s = %d;\n", sizes[k][s], s);
        fprintf(o, "    return &tab[s][id];\n}\n");
        if (k == 1)
            fprintf(o, "\n#define K_(id, k, n) k,\nstatic const char *const keys[] = { APPICON_LIST(K_) };\n"
                       "#define N_(id, k, n) n,\nstatic const char *const names[] = { APPICON_LIST(N_) };\n\n"
                       "static int ieq(const char *a, const char *b) {\n"
                       "    for (; *a && *b; a++, b++) if ((*a | 32) != (*b | 32)) return 0;\n"
                       "    return *a == *b;\n}\n\n"
                       "int appicon_find(const char *s) {\n"
                       "    for (int i = 0; s && i < APPICON_COUNT; i++) if (ieq(s, keys[i]) || ieq(s, names[i])) return i;\n"
                       "    return -1;\n}\n");
        fclose(o);
    }
    nsvgDeleteRasterizer(r);
    return 0;
}
