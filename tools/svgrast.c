/* svgrast.c - host tool: rasterise a tools/mkicons.py bundle with nanosvg (third_party/nanosvg, zlib licence).
 *   svgrast IN.bundle icons.c appicons.c fileicons.c
 * S records become A8 masks (icon<size>_<ID>), A/F records premultiplied ARGB behind one descriptor each
 * (appicon<size>_<ID>, fileicon<size>_<ID>). Every icon/size is its own symbol, so -fdata-sections + --gc-sections
 * link only what a binary references: icons.h's inline appicon_get/fileicon_get for the colour ones, the per-binary
 * icon_use table (mkicons.py --use) for the symbolic ones. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#define NANOSVG_IMPLEMENTATION
#include "nanosvg.h"
#define NANOSVGRAST_IMPLEMENTATION
#include "nanosvgrast.h"

static void die(const char *m) { fprintf(stderr, "svgrast: %s\n", m); exit(1); }

int main(int argc, char **argv) {
    if (argc != 5) die("usage: svgrast IN.bundle icons.c appicons.c fileicons.c");
    FILE *in = fopen(argv[1], "rb"), *out[3];
    if (!in) die("can't open bundle");
    for (int k = 0; k < 3; k++) {
        if (!(out[k] = fopen(argv[2 + k], "w"))) die("can't write output");
        fprintf(out[k], "/* generated by tools/svgrast.c from tools/mkicons.py - do not edit */\n#include \"icons.h\"\n\n");
    }
    static const char *pre[3] = { "icon", "appicon", "fileicon" };
    NSVGrasterizer *r = nsvgCreateRasterizer();
    char kind, id[64];
    int size, len;
    while (fscanf(in, " %c %63s %d %d", &kind, id, &size, &len) == 4) {
        fgetc(in);
        char *svg = malloc(len + 1);
        if (fread(svg, 1, len, in) != (size_t)len) die("short bundle");
        svg[len] = 0;
        int k = kind == 'S' ? 0 : kind == 'A' ? 1 : 2;
        NSVGimage *im = nsvgParse(svg, "px", 96);
        if (!im) die(id);
        unsigned char *px = calloc(size * size, 4);
        nsvgRasterize(r, im, 0, 0, (float)size / im->width, px, size, size, size * 4);
        FILE *f = out[k];
        if (k == 0) fprintf(f, "const uint8_t icon%d_%s[%d] = {\n    ", size, id, size * size);
        else fprintf(f, "static const uint32_t d%d_%s[%d] = {\n    ", size, id, size * size);
        int empty = 1;
        for (int i = 0; i < size * size; i++) {
            unsigned a = px[i * 4 + 3];
            if (a) empty = 0;
            if (k == 0) fprintf(f, "%u,", a);
            else {
                unsigned c[3];
                for (int j = 0; j < 3; j++) c[j] = (px[i * 4 + j] * a + 127) / 255;
                fprintf(f, "0x%x,", a << 24 | c[0] << 16 | c[1] << 8 | c[2]);
            }
            if (i % 32 == 31) fprintf(f, "\n    ");
        }
        fprintf(f, "};\n");
        if (k) fprintf(f, "const struct aicon %s%d_%s = { %d, %d, d%d_%s };\n", pre[k], size, id, size, size, size, id);
        if (empty) die(id);
        nsvgDelete(im);
        free(px);
        free(svg);
    }
    fprintf(out[0], "\nconst struct icon *icon_get(int id, int size) {\n"
                    "    if (id < 0 || id >= ICON_COUNT) return 0;\n"
                    "    const struct icon *i = icon_use[id];\n"
                    "    int s = size >= 48 && i[2].w ? 2 : size >= 20;\n"
                    "    return i[s].w ? &i[s] : 0;\n}\n");
    fprintf(out[1], "\n#define K_(id, k, n) k,\nstatic const char *const keys[] = { APPICON_LIST(K_) };\n"
                    "#define N_(id, k, n) n,\nstatic const char *const names[] = { APPICON_LIST(N_) };\n\n"
                    "static int ieq(const char *a, const char *b) {\n"
                    "    for (; *a && *b; a++, b++) if ((*a | 32) != (*b | 32)) return 0;\n"
                    "    return *a == *b;\n}\n\n"
                    "int appicon_find(const char *s) {\n"
                    "    for (int i = 0; s && i < APPICON_COUNT; i++) if (ieq(s, keys[i]) || ieq(s, names[i])) return i;\n"
                    "    return -1;\n}\n");
    for (int k = 0; k < 3; k++) fclose(out[k]);
    nsvgDeleteRasterizer(r);
    return 0;
}
